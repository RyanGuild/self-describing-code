//! Markdown view: the whole self-model as one reviewable file.
//!
//! This exists so the map can live in the repository and be read in an editor
//! with Mermaid support. It is generated, never hand-edited, and it must be
//! byte-stable across runs — the same rule as the `.mmd` files.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use robby_ir::{CoverageReport, Document, EdgeKind, Node, NodeId};

use crate::{flowchart, sequence, stable_id};

/// Render a complete Markdown report.
///
/// When `sources` is provided, each node's exact source slice is embedded next
/// to its diagram. That makes the file self-contained: one segment, its
/// process, and its provenance in the same place.
pub fn report(
    doc: &Document,
    coverage: Option<&CoverageReport>,
    sources: Option<&BTreeMap<String, String>>,
) -> String {
    let mut out = String::new();

    out.push_str("# Robby self-model\n\n");
    let _ = writeln!(
        out,
        "> Generated by `{}` · schema v{} · {} nodes\n",
        doc.generator,
        doc.schema_version,
        doc.nodes.len()
    );
    out.push_str(
        "This file is generated. Do not edit it by hand: run `robby report` instead.\n\n",
    );

    if let Some(report) = coverage {
        coverage_section(&mut out, report);
    }

    // Overview graph for each root.
    for root in &doc.roots {
        let _ = writeln!(out, "## Graph — `{}`\n", root);
        out.push_str("```mermaid\n");
        out.push_str(&flowchart(doc, root));
        out.push_str("```\n\n");
    }

    out.push_str("## Nodes\n\n");
    for root in &doc.roots {
        for node in doc.subtree(root) {
            node_section(&mut out, doc, node, sources);
        }
    }

    out
}

pub(crate) fn coverage_section(out: &mut String, report: &CoverageReport) {
    out.push_str("## Coverage\n\n");
    out.push_str("| File | Code | Claimed | Trivia | Status |\n");
    out.push_str("|---|---:|---:|---:|---|\n");

    for file in report.worst_first() {
        let status = if file.is_complete() {
            "ok".to_owned()
        } else {
            format!("**{} bytes unclaimed**", file.uncovered_bytes())
        };
        let _ = writeln!(
            out,
            "| `{}` | {:.1}% | {}/{} | {} | {} |",
            file.file,
            file.code_ratio() * 100.0,
            file.covered_bytes,
            file.covered_bytes + file.uncovered_bytes(),
            file.trivia_bytes(),
            status
        );
    }
    out.push('\n');

    let failures: Vec<_> = report.failures().collect();
    if failures.is_empty() {
        out.push_str("Every byte is owned by a node or classified as trivia.\n\n");
    } else {
        out.push_str("### Unclaimed code\n\n");
        for (file, gap) in failures {
            let _ = writeln!(
                out,
                "- `{}` — `{}` — `{}`",
                file.file,
                gap.span.location(),
                gap.preview
            );
        }
        out.push('\n');
    }
}

fn node_section(
    out: &mut String,
    doc: &Document,
    node: &Node,
    sources: Option<&BTreeMap<String, String>>,
) {
    let depth = heading_depth(doc, node);
    let hashes = "#".repeat(depth.min(6));

    let _ = writeln!(out, "{hashes} `{}`\n", node.fqn);
    let _ = writeln!(out, "| | |");
    let _ = writeln!(out, "|---|---|");
    let _ = writeln!(out, "| kind | `{}` |", node.kind);
    let _ = writeln!(out, "| id | `{}` |", node.id);
    if let Some(sig) = &node.signature {
        let _ = writeln!(out, "| signature | `{}` |", cell(sig));
    }
    if let Some(span) = &node.span {
        let _ = writeln!(out, "| location | `{}` |", span.location());
        let _ = writeln!(
            out,
            "| span | bytes {}..{} |",
            span.start.byte, span.end.byte
        );
    }
    let _ = writeln!(
        out,
        "| provenance | {} · confidence {:.2} |",
        source_name(node.provenance.source),
        node.provenance.confidence
    );
    if !node.tags.is_empty() {
        let _ = writeln!(out, "| tags | {} |", node.tags.join(", "));
    }
    out.push('\n');

    if let Some(docs) = &node.docs {
        for line in docs.lines() {
            let _ = writeln!(out, "> {line}");
        }
        out.push('\n');
    }

    if let Some(span) = &node.span {
        if let Some(source) = sources.and_then(|s| s.get(&span.file)) {
            if let Some(slice) = source.get(span.start.byte as usize..span.end.byte as usize) {
                out.push_str("```rust\n");
                out.push_str(slice.trim_end());
                out.push_str("\n```\n\n");
            }
        }
    }

    if let Some(process) = &node.process {
        out.push_str("```mermaid\n");
        out.push_str(&sequence(process));
        out.push_str("```\n\n");

        let observed = process.steps.iter().filter(|s| s.observed).count();
        let _ = writeln!(
            out,
            "{} steps · {} observed · {} possible only\n",
            process.steps.len(),
            observed,
            process.steps.len() - observed
        );
    }

    if !node.edges.is_empty() {
        let _ = writeln!(out, "**Edges**\n");
        for edge in &node.edges {
            let marker = if edge.resolved { "" } else { " (unresolved)" };
            let _ = writeln!(
                out,
                "- {} → `{}`{marker}",
                edge_name(edge.kind),
                edge.to
            );
        }
        out.push('\n');
    }

    if !node.children.is_empty() {
        let names: Vec<String> = node
            .children
            .iter()
            .filter_map(|c| doc.get(c))
            .map(|c| format!("`{}`", c.fqn))
            .collect();
        let _ = writeln!(out, "**Children** — {}\n", names.join(", "));
    }
}

fn heading_depth(doc: &Document, node: &Node) -> usize {
    let mut depth = 3;
    let mut current = node.parent.clone();
    while let Some(parent) = current {
        depth += 1;
        current = doc.get(&parent).and_then(|p| p.parent.clone());
    }
    depth
}

pub(crate) fn cell(input: &str) -> String {
    input.replace('|', "\\|").replace('\n', " ")
}

pub(crate) fn source_name(source: robby_ir::Source) -> &'static str {
    match source {
        robby_ir::Source::Extractor => "extractor",
        robby_ir::Source::Macro => "macro",
        robby_ir::Source::Trace => "trace",
        robby_ir::Source::Agent => "agent",
        robby_ir::Source::Hand => "hand",
    }
}

pub(crate) fn edge_name(kind: EdgeKind) -> &'static str {
    match kind {
        EdgeKind::Contains => "contains",
        EdgeKind::Calls => "calls",
        EdgeKind::Uses => "uses",
        EdgeKind::Imports => "imports",
        EdgeKind::Implements => "implements",
        EdgeKind::Extends => "extends",
        EdgeKind::Returns => "returns",
        EdgeKind::Field => "field",
        EdgeKind::References => "references",
    }
}

/// A compact index of every node, for the top of the report.
pub fn index(doc: &Document) -> String {
    let mut out = String::from("| Node | Kind | Location |\n|---|---|---|\n");
    let ids: Vec<&NodeId> = doc.nodes.keys().collect();
    for id in ids {
        let node = &doc.nodes[id];
        let location = node
            .span
            .as_ref()
            .map(|s| s.location())
            .unwrap_or_else(|| "—".to_owned());
        let _ = writeln!(
            out,
            "| `{}` | `{}` | `{}` |",
            node.fqn,
            node.kind,
            location
        );
    }
    out
}

/// Sanity check used by tests: every id has a deterministic short form.
pub fn anchor(id: &NodeId) -> String {
    stable_id(id.as_str())
}
