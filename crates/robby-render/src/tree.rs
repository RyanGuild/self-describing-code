fn global_index(doc: &Document, coverage: Option<&CoverageReport>, crates: &[&Node]) -> String {
    let mut out = String::new();
    out.push_str("# Robby self-model\n\n");
    let _ = writeln!(
        out,
        "> Generated by `{}` · schema v{} · {} nodes · {} files\n",
        doc.generator,
        doc.schema_version,
        doc.nodes.len(),
        doc.files.len()
    );
    out.push_str(
        "This tree is generated. Do not edit it by hand: run `cargo run -p robby-cli -- report`.\n\n",
    );

    if let Some(report) = coverage {
        coverage_section(&mut out, report);
    }

    out.push_str("## Crates\n\n");
    out.push_str("| Crate | Modules | Nodes |\n|---|---:|---:|\n");
    for krate in crates {
        let _ = writeln!(
            out,
            "| [`{}`]({}/index.md) | {} | {} |",
            krate.name,
            krate.name,
            count_modules(doc, krate),
            doc.subtree(&krate.id).len()
        );
    }
    out.push('\n');

    if !crates.is_empty() {
        out.push_str(&workspace_dependencies(doc));
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out.push('\n');
    }

    out.push_str("## Module tree\n\n");
    for krate in crates {
        let crate_dir = krate.name.clone();
        let _ = writeln!(out, "- [`{}`]({crate_dir}/index.md)", krate.name);
        for child in &krate.children {
            let Some(node) = doc.get(child) else { continue };
            if is_module(node) {
                module_tree_line(doc, node, &crate_dir, 1, &mut out);
            }
        }
    }
    out.push('\n');

    out
}

fn module_tree_line(
    doc: &Document,
    node: &Node,
    crate_dir: &str,
    depth: usize,
    out: &mut String,
) {
    let Some(index) = module_index_path(node, crate_dir) else {
        return;
    };
    let indent = "  ".repeat(depth);
    let _ = writeln!(
        out,
        "{indent}- [`{}`]({}) — {} nodes",
        short_fqn(node, crate_dir),
        index.to_string_lossy().replace('\\', "/"),
        doc.subtree(&node.id).len()
    );
    for child in &node.children {
        let Some(child) = doc.get(child) else { continue };
        if is_module(child) {
            module_tree_line(doc, child, crate_dir, depth + 1, out);
        }
    }
}

/// A module page: what is in here, and where to go next.
fn module_page(
    doc: &Document,
    node: &Node,
    crate_dir: &str,
    sources: Option<&BTreeMap<String, String>>,
    out_rel: &str,
) -> String {
    let mut out = String::new();
    let page = module_index_path(node, crate_dir).unwrap_or_else(|| PathBuf::from("README.md"));

    let _ = writeln!(out, "# `{}`\n", node.fqn);
    out.push_str(&nav(doc, node, &page, false));

    let _ = writeln!(out, "| | |");
    let _ = writeln!(out, "|---|---|");
    let _ = writeln!(out, "| kind | `{}` |", node.kind);
    if let Some(span) = &node.span {
        let _ = writeln!(out, "| declared at | {} |", source_link(&page, out_rel, span));
    }
    let _ = writeln!(
        out,
        "| provenance | {} · confidence {:.2} |",
        source_name(node.provenance.source),
        node.provenance.confidence
    );
    let _ = writeln!(out, "| nodes | {} |", doc.subtree(&node.id).len());
    out.push('\n');

    if let Some(docs) = &node.docs {
        for line in docs.lines() {
            let _ = writeln!(out, "> {line}");
        }
        out.push('\n');
    }

    let children: Vec<&Node> = node
        .children
        .iter()
        .filter_map(|child| doc.get(child))
        .collect();

    // Views → rendered sections → report artifact (one formal diagram per concern).
    let views = collect(
        doc,
        node,
        sources,
        &SelectOpts {
            hierarchy: false,
            hierarchy_depth: 0,
            hierarchy_all: false,
            sibling: false,
            source: false,
            types: true,
            dependencies: true,
            externals: true,
            comments: true,
            links: true,
            entry: true,
            process: false,
        },
    );
    let md = MarkdownRenderer::new();
    let mut report = Report::new();
    if let Some(entry) = &views.entry {
        report.push_titled("Entry", md.process(entry));
    }
    if let Some(types) = &views.types {
        report.push_titled("Types", md.types(types));
    }
    if let Some(deps) = &views.dependencies {
        for section in md.dependency_sections(deps) {
            report.push(section);
        }
    }
    if let Some(externals) = &views.externals {
        report.push_titled("Externals", md.externals(externals));
    }
    if let Some(comments) = &views.comments {
        report.push_titled("Comments", md.comments(comments));
    }
    out.push_str(&report.to_markdown());
    out.push_str(&render_links(doc, &views.links, &page));

    let submodules: Vec<&&Node> = children.iter().filter(|c| is_module(c)).collect();
    if !submodules.is_empty() {
        out.push_str("## Modules\n\n");
        for sub in submodules {
            if let Some(target) = module_index_path(sub, crate_dir) {
                let _ = writeln!(
                    out,
                    "- [`{}`]({}) — {} nodes",
                    short_fqn(sub, crate_dir),
                    rel_link(&page, &target),
                    doc.subtree(&sub.id).len()
                );
            }
        }
        out.push('\n');
    }

    let mut imports: Vec<&Node> = Vec::new();
    let mut items: Vec<&Node> = Vec::new();
    for child in &children {
        match child.kind.as_str() {
            kind::code::IMPORT => imports.push(child),
            k if is_module_kind(k) => {}
            k if is_compact(k) => {}
            _ => items.push(child),
        }
    }

    if !items.is_empty() {
        let module_dir = page.parent().unwrap_or(Path::new("."));
        let slugs = item_slugs(&items);
        out.push_str("## Items\n\n");
        out.push_str("| Item | Kind | Steps | Location |\n|---|---|---:|---|\n");
        for item in items {
            let Some(slug) = slugs.get(&item.id) else { continue };
            let target = module_dir.join(format!("{slug}.md"));
            let location = item
                .span
                .as_ref()
                .map(|span| span.location())
                .unwrap_or_else(|| "—".to_owned());
            let steps = item
                .process
                .as_ref()
                .map(|process| process.steps.len().to_string())
                .unwrap_or_else(|| "—".to_owned());
            let _ = writeln!(
                out,
                "| [`{}`]({}) | `{}` | {} | `{}` |",
                item.name,
                rel_link(&page, &target),
                item.kind,
                steps,
                location
            );
        }
        out.push('\n');
    }

    if !imports.is_empty() {
        out.push_str("## Imports\n\n");
        for import in imports {
            let text = sources
                .and_then(|s| import.span.as_ref().and_then(|span| slice(s, span)))
                .map(|text| first_line(&text))
                .unwrap_or_else(|| import.name.clone());
            let _ = writeln!(out, "- {}", linked_import(doc, &page, &text));
        }
        out.push('\n');
    }

    out
}

/// An item page: the source, its process, its edges.
fn item_page(
    doc: &Document,
    node: &Node,
    page: &Path,
    sources: Option<&BTreeMap<String, String>>,
    out_rel: &str,
) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# `{}`\n", node.fqn);
    out.push_str(&nav(doc, node, page, true));
    render_node(&mut out, doc, node, 2, page, sources, out_rel, false);
    out
}

fn nav(doc: &Document, node: &Node, page: &Path, item: bool) -> String {
    let mut out = String::new();
    let _ = write!(out, "[Self-model]({})", rel_link(page, Path::new("README.md")));

    let crate_dir = crate_of(node).unwrap_or_default();

    let parent_target = if item {
        node.parent
            .as_ref()
            .and_then(|id| doc.get(id))
            .and_then(|parent| module_index_path(parent, &crate_dir))
    } else {
        node.parent
            .as_ref()
            .and_then(|id| doc.get(id))
            .and_then(|parent| {
                if is_crate(parent) {
                    Some(crate_index_path(&crate_dir))
                } else {
                    module_index_path(parent, &crate_dir)
                }
            })
    };

    if let Some(target) = parent_target {
        let label = if item {
            node.parent
                .as_ref()
                .and_then(|id| doc.get(id))
                .map(|parent| short_fqn(parent, &crate_dir))
                .unwrap_or_default()
        } else {
            node.parent
                .as_ref()
                .and_then(|id| doc.get(id))
                .map(|parent| short_fqn(parent, &crate_dir))
                .unwrap_or_else(|| "crate".to_owned())
        };
        let _ = write!(out, " · [{}]({})", label, rel_link(page, &target));
    }

    out.push_str("\n\n");
    out
}

