//! The self-model as a linked set of pages instead of one enormous file.
//!
//! Layout mirrors the code's own hierarchy:
//!
//! ```text
//! docs/self-model/README.md                     global index
//! docs/self-model/<crate>/index.md              crate overview
//! docs/self-model/<crate>/<module>/index.md     module overview
//! docs/self-model/<crate>/<module>/<item>.md    one item, with its process
//! ```
//!
//! Every page is generated from the same IR. Nothing is summarized away: an
//! item page holds the exact source slice, the process diagram, and the edges.
//! What changes is *where* you read it, which is the whole point of progressive
//! rendering.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use robby_ir::{CoverageReport, Document, Node, NodeId, kind};

use crate::markdown::{cell, coverage_section, edge_name, source_name};
use crate::render::{MarkdownRenderer, Renderer};
use crate::report::Report;
use crate::view::{LinkGraph, SelectOpts, collect};
use crate::{sequence, workspace_dependencies};

/// One generated page.
pub struct Page {
    pub path: PathBuf,
    pub body: String,
}

/// Build every page of the self-model.
///
/// `out_rel` is the output directory relative to the workspace root, e.g.
/// `docs/self-model`. It is only used to compute links back to source files.
pub fn tree(
    doc: &Document,
    coverage: Option<&CoverageReport>,
    sources: Option<&BTreeMap<String, String>>,
    out_rel: &str,
) -> Vec<Page> {
    let mut pages = Vec::new();

    let crates: Vec<&Node> = doc
        .nodes
        .values()
        .filter(|node| is_crate(node))
        .collect();

    pages.push(Page {
        path: PathBuf::from("README.md"),
        body: global_index(doc, coverage, &crates),
    });

    for krate in crates {
        let crate_dir = krate.name.clone();
        module_pages(doc, krate, &crate_dir, &mut pages, sources, out_rel);
    }

    pages
}

fn module_pages(
    doc: &Document,
    node: &Node,
    crate_dir: &str,
    pages: &mut Vec<Page>,
    sources: Option<&BTreeMap<String, String>>,
    out_rel: &str,
) {
    let Some(index) = module_index_path(node, crate_dir) else {
        return;
    };

    pages.push(Page {
        path: index.clone(),
        body: module_page(doc, node, crate_dir, sources, out_rel),
    });

    let module_dir = index.parent().unwrap_or(Path::new(".")).to_path_buf();
    let items = item_children(doc, node);
    let slugs = item_slugs(&items);

    for child in &node.children {
        let Some(child) = doc.get(child) else { continue };
        if is_module(child) {
            module_pages(doc, child, crate_dir, pages, sources, out_rel);
        }
    }

    for item in items {
        let Some(slug) = slugs.get(&item.id) else { continue };
        let path = module_dir.join(format!("{slug}.md"));
        pages.push(Page {
            path: path.clone(),
            body: item_page(doc, item, &path, sources, out_rel),
        });
    }
}

/// Direct, non-module, non-trivial children of a module, in source order.
fn item_children<'a>(doc: &'a Document, node: &Node) -> Vec<&'a Node> {
    node.children
        .iter()
        .filter_map(|child| doc.get(child))
        .filter(|child| {
            !is_module(child) && !is_compact(child.kind.as_str())
        })
        .collect()
}

/// Page slugs for a module's items. `index` is reserved for the module page.
fn item_slugs(items: &[&Node]) -> BTreeMap<NodeId, String> {
    let mut used = BTreeSet::new();
    used.insert("index".to_owned());
    let mut slugs = BTreeMap::new();
    for item in items {
        let slug = item_slug(&item.name, &item.id, &mut used);
        slugs.insert(item.id.clone(), slug);
    }
    slugs
}

